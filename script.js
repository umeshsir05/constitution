// ---------- render questions ----------
function renderQuestions(filterText = '') {
    const filtered = filterText.trim() === '' 
        ? validQuestions 
        : validQuestions.filter(q => 
            q.q.toLowerCase().includes(filterText.toLowerCase()) || 
            q.options.some(opt => opt.toLowerCase().includes(filterText.toLowerCase())) ||
            q.answer.toLowerCase().includes(filterText.toLowerCase())
          );

    if (filtered.length === 0) {
        container.innerHTML = `<div class="no-results">😕 कोई प्रश्न नहीं मिला। कृपया अन्य शब्द खोजें।</div>`;
        return;
    }

    let html = '';
    filtered.forEach((item, index) => {
        const qNum = index + 1;
        let questionText = item.q;
        let answerText = item.answer;
        let optionTexts = item.options;
        const searchTerm = filterText.trim();
        if (searchTerm !== '') {
            const regex = new RegExp(`(${searchTerm.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')})`, 'gi');
            questionText = questionText.replace(regex, '<span class="highlight">$1</span>');
            answerText = answerText.replace(regex, '<span class="highlight">$1</span>');
            optionTexts = optionTexts.map(opt => opt.replace(regex, '<span class="highlight">$1</span>'));
        }

        html += `
            <div class="card">
                <div class="question">
                    <span class="q-num">${qNum}.</span>
                    <span>${questionText}</span>
                </div>
                <div class="options">
                    ${optionTexts.map((opt, i) => `<div class="option">${String.fromCharCode(97 + i)}) ${opt}</div>`).join('')}
                </div>
                <div class="answer-box">✅ उत्तर: ${answerText}</div>
            </div>
        `;
    });
    container.innerHTML = html;
}

// initial render
renderQuestions();

// search listener
searchInput.addEventListener('input', (e) => {
    renderQuestions(e.target.value);
});

// ---------- Drawer logic ----------
function openDrawer() {
    navDrawer.classList.add('open');
    overlay.classList.add('active');
}

function closeDrawer() {
    navDrawer.classList.remove('open');
    overlay.classList.remove('active');
}

menuIcon.addEventListener('click', openDrawer);
closeDrawerBtn.addEventListener('click', closeDrawer);
overlay.addEventListener('click', closeDrawer);

// close drawer and scroll to top
function closeDrawerAndScroll() {
    closeDrawer();
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

function scrollToTop() {
    window.scrollTo({ top: 0, behavior: 'smooth' });
} 

function scrollToBottom() {
    window.scrollTo({ top: document.body.scrollHeight, behavior: 'smooth' });
}


// ---------- Dark mode ----------
function toggleDarkMode() {
    document.body.classList.toggle('dark');
    const isDark = document.body.classList.contains('dark');
    localStorage.setItem('mcq-theme', isDark ? 'dark' : 'light');
}

// load saved theme
const savedTheme = localStorage.getItem('mcq-theme');
if (savedTheme === 'dark') {
    document.body.classList.add('dark');
} else if (savedTheme === 'light') {
    document.body.classList.remove('dark');
} else if (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
    document.body.classList.add('dark');
}

window.toggleDarkMode = toggleDarkMode;

// close drawer on Escape key
document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && navDrawer.classList.contains('open')) {
        closeDrawer();
    }
});
